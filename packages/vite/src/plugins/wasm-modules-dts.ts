import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import type { Plugin } from "vite";
import { GwenError } from "@gwenjs/schema";
import { ViteErrorCodes } from "../error-codes.js";
import { devHint } from "../pipeline/dev-hint.js";
import { scanWasmModuleNames, type WasmModuleHit } from "../scanners/index.js";
import type { GwenViteOptions } from "../types.js";

/** Options of the `gwen:wasm-modules-dts` plugin. */
export interface WasmModulesDtsOptions {
  /**
   * Extra directories to scan besides `src`, relative to the project root.
   * Read at `buildStart` and on each hot update. `false` and `undefined` entries are ignored.
   */
  dirs?: () => readonly (string | false | undefined)[];
}

const SOURCE_SUFFIXES = [".ts", ".tsx", ".js", ".jsx"];
const HEADER = "// Generated by gwen — do not edit";

/** One `GwenWasmModules` entry: the type import behind a name, and the call that gave it. */
interface WasmEntry {
  name: string;
  /** Import specifier as written in the `.d.ts`, a relative one resolved against the types dir. */
  from: string;
  /** Original export name of the type. */
  exported: string;
  hit: WasmModuleHit;
}

function posix(path: string): string {
  return path.split(sep).join("/");
}

function endsWithSource(file: string): boolean {
  return SOURCE_SUFFIXES.some((suffix) => file.endsWith(suffix));
}

/**
 * Vite sub-plugin that writes `.gwen/types/wasm-modules.d.ts`.
 *
 * Scans `src` and the local plugin and module directories for `loadWasmModule<T>({ name })`
 * calls (`scanWasmModuleNames`) and writes one `GwenWasmModules` entry per name, so
 * `getWasmModule("name")` and `useWasmModule("name")` are typed with no hand-written
 * augmentation. A call that cannot be typed is listed as a `// skipped` comment.
 *
 * Runs at `buildStart` and again on `handleHotUpdate` for a saved source file under a scanned
 * directory. Vite reports no file creation or deletion to `handleHotUpdate`: restart the dev
 * server after adding or deleting a file that holds a call. The file is rewritten only when its
 * content changes. `dts: false` writes nothing.
 * Two different types under one name throw `VITE:WASM_MODULE_DUPLICATE` before any write.
 */
export function gwenWasmModulesDtsPlugin(options: GwenViteOptions & WasmModulesDtsOptions): Plugin {
  const gwenDir = options.gwenDir ?? ".gwen";
  let root = process.cwd();

  function scannedDirs(): string[] {
    const dirs = ["src"];
    for (const dir of options.dirs?.() ?? []) {
      if (typeof dir === "string") dirs.push(dir);
    }
    return dirs;
  }

  function isScanned(file: string): boolean {
    if (!endsWithSource(file)) return false;
    const normalized = posix(file);
    return scannedDirs().some((dir) => normalized.startsWith(`${posix(resolve(root, dir))}/`));
  }

  function rootRelative(file: string): string {
    return posix(relative(root, file));
  }

  function duplicateError(first: WasmEntry, second: WasmEntry): GwenError {
    const where = (entry: WasmEntry): string => `${rootRelative(entry.hit.file)}:${entry.hit.line}`;
    return new GwenError(
      ViteErrorCodes.WASM_MODULE_DUPLICATE,
      `loadWasmModule name "${first.name}" is declared with two types (${where(first)}, ${where(second)}).`,
      { composable: "gwen", hint: devHint("Give each name one type, or rename one module.") },
    );
  }

  /** One entry per name, sorted by name. The first conflict found is returned, not thrown. */
  function indexEntries(
    hits: readonly WasmModuleHit[],
    typesDir: string,
  ): { entries: WasmEntry[]; conflict: GwenError | undefined } {
    const byName = new Map<string, WasmEntry>();
    let conflict: GwenError | undefined;
    for (const hit of hits) {
      const { from, name: exported } = hit.typeImport;
      const specifier = from.startsWith(".")
        ? posix(relative(typesDir, resolve(dirname(hit.file), from)))
        : from;
      const entry: WasmEntry = { name: hit.name, from: specifier, exported, hit };
      const known = byName.get(hit.name);
      if (known === undefined) {
        byName.set(hit.name, entry);
      } else if (known.from !== entry.from || known.exported !== entry.exported) {
        conflict ??= duplicateError(known, entry);
      }
    }
    const entries = [...byName.values()].sort((a, b) => (a.name < b.name ? -1 : 1));
    return { entries, conflict };
  }

  function render(entries: readonly WasmEntry[], skips: readonly string[]): string {
    const lines = [HEADER];
    entries.forEach((entry, index) => {
      lines.push(
        `import type { ${entry.exported} as _T${index} } from ${JSON.stringify(entry.from)};`,
      );
    });
    lines.push('declare module "@gwenjs/core" {');
    if (entries.length === 0) {
      lines.push("  interface GwenWasmModules {}");
    } else {
      lines.push("  interface GwenWasmModules {");
      entries.forEach((entry, index) => {
        lines.push(`    ${JSON.stringify(entry.name)}: _T${index};`);
      });
      lines.push("  }");
    }
    lines.push("}");
    lines.push(...skips);
    lines.push("export {};");
    return `${lines.join("\n")}\n`;
  }

  function regenerate(): void {
    if (options.dts === false) return;
    const typesDir = resolve(root, gwenDir, "types");
    const scan = scanWasmModuleNames(root, scannedDirs());
    const { entries, conflict } = indexEntries(scan.hits, typesDir);
    if (conflict !== undefined) throw conflict;
    const skips = scan.skipped.map(
      (skip) => `// skipped ${rootRelative(skip.file)}:${skip.line}: ${skip.reason}`,
    );
    const content = render(entries, skips);
    const dest = join(typesDir, "wasm-modules.d.ts");
    mkdirSync(typesDir, { recursive: true });
    const existing = existsSync(dest) ? readFileSync(dest, "utf-8") : "";
    if (existing !== content) writeFileSync(dest, content, "utf-8");
  }

  return {
    name: "gwen:wasm-modules-dts",

    configResolved(config) {
      root = config.root;
    },

    buildStart() {
      regenerate();
    },

    handleHotUpdate({ file }: { file: string }) {
      if (!isScanned(file)) return;
      regenerate();
    },
  };
}
