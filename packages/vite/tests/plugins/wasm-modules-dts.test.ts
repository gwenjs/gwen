import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  utimesSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import type { Plugin } from "vite";
import {
  gwenWasmModulesDtsPlugin,
  type WasmModulesDtsOptions,
} from "../../src/plugins/wasm-modules-dts.js";
import type { GwenViteOptions } from "../../src/types.js";

const HEADER = "// Generated by gwen — do not edit";
const NO_FILE = "<no file>";
const DUPLICATE = "VITE:WASM_MODULE_DUPLICATE";

const P1_TEXT = [
  HEADER,
  'import type { NavExports as _T0 } from "../../src/plugins/nav-types";',
  'declare module "@gwenjs/core" {',
  "  interface GwenWasmModules {",
  '    "nav": _T0;',
  "  }",
  "}",
  "// skipped src/s.ts:2: non-literal name",
  "export {};",
  "",
].join("\n");

const EMPTY_TEXT = [
  HEADER,
  'declare module "@gwenjs/core" {',
  "  interface GwenWasmModules {}",
  "}",
  "export {};",
  "",
].join("\n");

let root = "";

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "gwen-wasm-modules-dts-"));
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

function write(rel: string, source: string): string {
  const full = join(root, rel);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, source);
  return full;
}

/** A source file with one `loadWasmModule` call typed by `type` imported from `from`. */
function callSource(name: string, type: string, from: string): string {
  return [
    `import type { ${type} } from "${from}";`,
    `engine.loadWasmModule<${type}>({ name: "${name}" });`,
    "",
  ].join("\n");
}

function dtsPath(gwenDir = ".gwen"): string {
  return join(root, gwenDir, "types", "wasm-modules.d.ts");
}

function dtsText(gwenDir = ".gwen"): string {
  const file = dtsPath(gwenDir);
  return existsSync(file) ? readFileSync(file, "utf8") : NO_FILE;
}

function makePlugin(options: GwenViteOptions & WasmModulesDtsOptions = {}): Plugin {
  const plugin = gwenWasmModulesDtsPlugin(options);
  const configResolved = plugin.configResolved;
  if (typeof configResolved !== "function")
    throw new Error("gwen:wasm-modules-dts has no configResolved");
  Reflect.apply(configResolved, plugin, [{ root }]);
  return plugin;
}

function buildStart(plugin: Plugin): void {
  const hook = plugin.buildStart;
  if (typeof hook !== "function") throw new Error("gwen:wasm-modules-dts has no buildStart");
  Reflect.apply(hook, plugin, []);
}

function hotUpdate(plugin: Plugin, file: string): void {
  const hook = plugin.handleHotUpdate;
  if (typeof hook !== "function") throw new Error("gwen:wasm-modules-dts has no handleHotUpdate");
  Reflect.apply(hook, plugin, [{ file }]);
}

interface Thrown {
  code: string;
  message: string;
}

function thrownFields(caught: unknown): Thrown | undefined {
  if (typeof caught !== "object" || caught === null) return undefined;
  if (!("code" in caught) || !("message" in caught)) return undefined;
  const { code, message } = caught;
  if (typeof code !== "string" || typeof message !== "string") return undefined;
  return { code, message };
}

function thrownBy(run: () => void): Thrown | undefined {
  try {
    run();
  } catch (caught) {
    return thrownFields(caught);
  }
  return undefined;
}

function countOf(text: string, needle: string): number {
  return text.split(needle).length - 1;
}

describe("gwen:wasm-modules-dts", () => {
  it("writes an entry for a literal name with an importable type", () => {
    write(
      "src/plugins/nav.ts",
      [
        'import type { NavExports } from "./nav-types";',
        'engine.loadWasmModule<NavExports>({ name: "nav" });',
        "",
      ].join("\n"),
    );
    write(
      "src/s.ts",
      [
        'import type { Other } from "./other";',
        "engine.loadWasmModule<Other>({ name: dynamic });",
        "",
      ].join("\n"),
    );
    buildStart(makePlugin());
    expect(dtsText()).toBe(P1_TEXT);
  });

  it("keeps a bare specifier and the original name of an aliased type import", () => {
    write("src/lib.ts", callSource("lib", "Real", "some-lib"));
    buildStart(makePlugin());
    const text = dtsText();
    expect(text).toContain('import type { Real as _T0 } from "some-lib";');
    expect(text).toContain('"lib": _T0;');
  });

  it("lists one skipped line per skipped call and drops no other entry", () => {
    write(
      "src/s.ts",
      [
        'import type { A } from "./a";',
        "engine.loadWasmModule<A>({ name: dynamic });",
        'engine.loadWasmModule<A>({ name: "kept" });',
        "",
      ].join("\n"),
    );
    buildStart(makePlugin());
    const text = dtsText();
    expect(text).toContain('"kept": _T0;');
    expect(text).toContain("// skipped src/s.ts:2: non-literal name");
    expect(countOf(text, "// skipped")).toBe(1);
  });

  it("two files with one name and one type produce one entry", () => {
    write("src/a.ts", callSource("nav", "NavExports", "./nav-types"));
    write("src/sub/b.ts", callSource("nav", "NavExports", "../nav-types"));
    write("src/c.ts", callSource("nav", "NavExports", "./nav-types"));
    const thrown = thrownBy(() => buildStart(makePlugin()));
    expect(thrown).toBeUndefined();
    expect(countOf(dtsText(), '"nav":')).toBe(1);
  });

  it("two files with one name and two types raise VITE:WASM_MODULE_DUPLICATE naming both locations", () => {
    const first = callSource("nav", "NavExports", "./nav-types");
    write("src/a.ts", first);
    write("src/b.ts", first.replaceAll("NavExports", "OtherExports"));
    const thrown = thrownBy(() => buildStart(makePlugin()));
    expect(thrown?.code).toBe(DUPLICATE);
    expect(thrown?.message ?? "").toContain(
      'loadWasmModule name "nav" is declared with two types (src/a.ts:2, src/b.ts:2).',
    );
    expect(dtsText()).toBe(NO_FILE);
  });

  it("rewrites only when the content changes", () => {
    write("src/a.ts", callSource("nav", "NavExports", "./nav-types"));
    const plugin = makePlugin();
    buildStart(plugin);
    const file = dtsPath();
    expect(existsSync(file)).toBe(true);
    const past = new Date("2020-01-01T00:00:00.000Z");
    utimesSync(file, past, past);
    const before = statSync(file).mtimeMs;
    buildStart(plugin);
    expect(statSync(file).mtimeMs).toBe(before);
  });

  it("zero hits writes an empty augmentation that stays a module", () => {
    write("src/a.ts", "export const a = 1;\n");
    buildStart(makePlugin());
    expect(dtsText()).toBe(EMPTY_TEXT);
  });

  it("a removed call clears its entry on the next buildStart", () => {
    const source = write("src/a.ts", callSource("nav", "NavExports", "./nav-types"));
    const plugin = makePlugin();
    buildStart(plugin);
    expect(dtsText()).toContain('"nav"');
    writeFileSync(source, "export const a = 1;\n");
    buildStart(plugin);
    const text = dtsText();
    expect(text).not.toContain('"nav"');
    expect(text).toContain("interface GwenWasmModules {}");
  });

  it("handleHotUpdate rewrites for a saved file under a scanned directory and ignores another", () => {
    const inside = write("src/a.ts", callSource("nav", "NavExports", "./nav-types"));
    const outside = write("tools/b.ts", callSource("tool", "ToolExports", "./tool-types"));
    const plugin = makePlugin();
    hotUpdate(plugin, outside);
    expect(existsSync(dtsPath())).toBe(false);
    hotUpdate(plugin, inside);
    const text = dtsText();
    expect(text).toContain('"nav": _T0;');
    expect(text).not.toContain('"tool"');
  });

  it("numbers the type aliases in name order, not in file order", () => {
    write("src/a.ts", callSource("zeta", "ZetaExports", "./zeta-types"));
    write("src/b.ts", callSource("alpha", "AlphaExports", "./alpha-types"));
    buildStart(makePlugin());
    const text = dtsText();
    expect(text).toContain('import type { AlphaExports as _T0 } from "../../src/alpha-types";');
    expect(text).toContain('import type { ZetaExports as _T1 } from "../../src/zeta-types";');
    expect(text.indexOf("as _T0")).toBeLessThan(text.indexOf("as _T1"));
    expect(text).toContain('    "alpha": _T0;');
    expect(text).toContain('    "zeta": _T1;');
    expect(text.indexOf('"alpha": _T0;')).toBeLessThan(text.indexOf('"zeta": _T1;'));
  });

  it("handleHotUpdate ignores a sibling directory with the same prefix and a non-source extension", () => {
    const sibling = write("src2/a.ts", callSource("sibling", "SiblingExports", "./sibling-types"));
    const style = write("src/a.css", "body { color: red; }\n");
    const real = write("src/x.ts", callSource("real", "RealExports", "./real-types"));
    const plugin = makePlugin();
    hotUpdate(plugin, sibling);
    expect(existsSync(dtsPath())).toBe(false);
    hotUpdate(plugin, style);
    expect(existsSync(dtsPath())).toBe(false);
    hotUpdate(plugin, real);
    const text = dtsText();
    expect(text).toContain('"real": _T0;');
    expect(text).not.toContain('"sibling"');
  });

  it("scans a local directory outside src and ignores a directory set to false", () => {
    write("custom/plugins/c.ts", callSource("custom", "CustomExports", "./custom-types"));
    buildStart(makePlugin({ dirs: () => ["custom/plugins", false] }));
    const text = dtsText();
    expect(text).toContain('"custom": _T0;');
    expect(countOf(text, "interface GwenWasmModules")).toBe(1);
  });

  it("writes nothing when dts is false and honours gwenDir", () => {
    write("src/a.ts", callSource("nav", "NavExports", "./nav-types"));
    buildStart(makePlugin({ dts: false }));
    expect(existsSync(dtsPath())).toBe(false);
    buildStart(makePlugin({ gwenDir: ".out" }));
    expect(existsSync(dtsPath(".out"))).toBe(true);
    expect(existsSync(dtsPath())).toBe(false);
  });

  it("a duplicate found on hot update throws and keeps the previous file", () => {
    write("src/a.ts", callSource("nav", "NavExports", "./nav-types"));
    const plugin = makePlugin();
    buildStart(plugin);
    const previous = dtsText();
    expect(previous).toContain('"nav": _T0;');
    const added = write("src/b.ts", callSource("nav", "OtherExports", "./nav-types"));
    const thrown = thrownBy(() => hotUpdate(plugin, added));
    expect(thrown?.code).toBe(DUPLICATE);
    expect(dtsText()).toBe(previous);
  });
});
