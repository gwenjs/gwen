import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  utimesSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { generateScenesDts } from "@gwenjs/app";
import { GwenApp, type ResolvedGwenConfig } from "@gwenjs/app/resolve";
import { gwen } from "../../src/index.js";
import { ViteErrorCodes } from "../../src/error-codes.js";
import { resolveMainScene, scanScenes } from "../../src/scanners/index.js";

const SORTED_DTS = [
  "// .gwen/types/scenes.d.ts — generated by GWEN, do not edit",
  'declare module "@gwenjs/schema" {',
  '  interface GwenSceneRegistry { "game": true; "menu": true; "we\\"ird": true }',
  "}",
  "export {};",
  "",
].join("\n");

const EMPTY_DTS = [
  "// .gwen/types/scenes.d.ts — generated by GWEN, do not edit",
  'declare module "@gwenjs/schema" {',
  "  interface GwenSceneRegistry {}",
  "}",
  "export {};",
  "",
].join("\n");

function makeConfig(): ResolvedGwenConfig {
  return {
    modules: [],
    engine: {
      maxEntities: 1000,
      targetFPS: 60,
      variant: "light",
      loop: "internal",
      maxDeltaSeconds: 0.1,
      debug: false,
      physicsHz: 0,
      maxCatchupSteps: 2,
    },
    logger: {
      minLevel: "warn",
    },
  };
}

function scenesFile(root: string): string {
  return join(root, ".gwen", "types", "scenes.d.ts");
}

async function prepareWithScenes(
  appInstance: GwenApp,
  rootDir: string,
  sceneNames: readonly string[],
): Promise<void> {
  await appInstance.setupModules(makeConfig());
  await appInstance.prepare(rootDir, { sceneNames });
}

function thrownFields(caught: unknown): { code: string; message: string } | undefined {
  if (typeof caught !== "object" || caught === null) return undefined;
  if (!("code" in caught) || !("message" in caught)) return undefined;
  const code = caught.code;
  const message = caught.message;
  if (typeof code !== "string" || typeof message !== "string") return undefined;
  return { code, message };
}

function thrownText(caught: unknown): string {
  if (caught === undefined) return "the call returned without throwing";
  if (caught instanceof Error) return caught.message;
  return "thrown value was not an Error";
}

function writeScene(root: string, fileName: string, source: string): void {
  const dir = join(root, "src", "scenes");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, fileName), source);
}

class FakeWatcher {
  readonly handlers = new Map<string, Array<(filePath: string) => void>>();

  add(_target: string): void {}

  on(event: string, handler: (filePath: string) => void): void {
    const list = this.handlers.get(event) ?? [];
    list.push(handler);
    this.handlers.set(event, list);
  }

  emit(event: string, filePath: string): void {
    for (const handler of this.handlers.get(event) ?? []) handler(filePath);
  }
}

let root: string;

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "gwen-scenes-dts-"));
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe("scenes.d.ts", () => {
  it("generateScenesDts sorts and escapes names", () => {
    expect(generateScenesDts(["menu", "game", 'we"ird'])).toBe(SORTED_DTS);
  });

  it("scanScenes throws VITE:SCENE_NAME_DUPLICATE naming both files", () => {
    writeScene(root, "alpha.ts", 'export const Alpha = defineScene("shared", () => {});\n');
    writeScene(root, "beta.ts", 'export const Beta = defineScene("shared", () => {});\n');
    let caught: unknown;
    try {
      scanScenes(root);
    } catch (error) {
      caught = error;
    }
    const fields = thrownFields(caught);
    expect(fields?.code, thrownText(caught)).toBe(ViteErrorCodes.SCENE_NAME_DUPLICATE);
    expect(fields?.message ?? "").toContain("src/scenes/alpha.ts");
    expect(fields?.message ?? "").toContain("src/scenes/beta.ts");
  });

  it("scanScenes throws VITE:SCENE_NAME_UNRESOLVED for a file with no literal name", () => {
    writeScene(root, "_helpers.ts", "export default defineScene(name, () => {})\n");
    writeScene(root, "loose.ts", "export default defineScene(name, () => {})\n");
    let caught: unknown;
    try {
      scanScenes(root);
    } catch (error) {
      caught = error;
    }
    const fields = thrownFields(caught);
    expect(fields?.code, thrownText(caught)).toBe(ViteErrorCodes.SCENE_NAME_UNRESOLVED);
    expect(fields?.message ?? "").toContain("src/scenes/loose.ts");
    expect(fields?.message ?? "").toContain("has no literal scene name.");
    expect(fields?.message ?? "").not.toContain("_helpers");
  });

  it("resolveMainScene throws VITE:MAIN_SCENE_UNKNOWN listing discovered names", () => {
    writeScene(root, "game.ts", 'export const Game = defineScene("game", () => {});\n');
    writeScene(root, "menu.ts", 'export const Menu = defineScene("menu", () => {});\n');
    const scenes = scanScenes(root);
    let caught: unknown;
    try {
      resolveMainScene(scenes, "missing");
    } catch (error) {
      caught = error;
    }
    const fields = thrownFields(caught);
    expect(fields?.code, thrownText(caught)).toBe(ViteErrorCodes.MAIN_SCENE_UNKNOWN);
    expect(fields?.message ?? "").toContain("game");
    expect(fields?.message ?? "").toContain("menu");
  });

  it("zero scenes gives an empty registry file", async () => {
    const appInstance = new GwenApp();
    await prepareWithScenes(appInstance, root, []);
    const file = scenesFile(root);
    expect(existsSync(file)).toBe(true);
    expect(readFileSync(file, "utf8")).toBe(EMPTY_DTS);
  });

  it("the file is not rewritten when unchanged", async () => {
    const appInstance = new GwenApp();
    await prepareWithScenes(appInstance, root, ["game"]);
    const file = scenesFile(root);
    expect(existsSync(file)).toBe(true);
    const past = new Date("2020-01-01T00:00:00.000Z");
    utimesSync(file, past, past);
    const before = statSync(file).mtimeMs;
    await prepareWithScenes(appInstance, root, ["game"]);
    expect(statSync(file).mtimeMs).toBe(before);
  });

  it("GwenApp.prepare writes the same file", async () => {
    const appInstance = new GwenApp();
    const names = ["menu", "game", 'we"ird'] as const;
    await prepareWithScenes(appInstance, root, names);
    const file = scenesFile(root);
    expect(existsSync(file)).toBe(true);
    const written = readFileSync(file, "utf8");
    expect(written).toBe(SORTED_DTS);
    expect(written).toBe(generateScenesDts(names));
  });

  it("a dev rescan error keeps the previous scenes.d.ts", async () => {
    writeFileSync(join(root, "gwen.config.ts"), "export default { modules: [] };\n");
    const scenePath = join(root, "src", "scenes", "a.ts");
    writeScene(root, "a.ts", 'export const A = defineScene("a", () => {});\n');
    const plugins = gwen({ watch: false });
    const plugin = plugins.find((item) => item.name === "gwen");
    if (plugin === undefined) throw new Error('gwen() did not return the "gwen" plugin');

    const configResolved = plugin.configResolved;
    if (typeof configResolved !== "function") throw new Error("gwen plugin has no configResolved");
    Reflect.apply(configResolved, plugin, [{ root }]);

    const buildStart = plugin.buildStart;
    if (typeof buildStart !== "function") throw new Error("gwen plugin has no buildStart");
    await Reflect.apply(buildStart, plugin, []);

    const file = scenesFile(root);
    expect(existsSync(file)).toBe(true);
    const previous = readFileSync(file, "utf8");

    writeFileSync(scenePath, "export default defineScene(name, () => {})\n");
    const logged: string[] = [];
    const watcher = new FakeWatcher();
    const server = {
      config: {
        root,
        logger: {
          error(message: string): void {
            logged.push(message);
          },
        },
      },
      watcher,
      moduleGraph: {
        getModuleById(): null {
          return null;
        },
        invalidateModule(): void {},
      },
      ws: {
        send(): void {},
      },
      middlewares: {
        use(): void {},
      },
    };
    const configureServer = plugin.configureServer;
    if (typeof configureServer !== "function") {
      throw new Error("gwen plugin has no configureServer");
    }
    Reflect.apply(configureServer, plugin, [server]);

    let thrown: unknown;
    try {
      watcher.emit("change", scenePath);
    } catch (error) {
      thrown = error;
    }
    expect(thrown).toBeUndefined();
    expect(readFileSync(file, "utf8")).toBe(previous);
    expect(logged.join("\n")).toContain("VITE:SCENE_NAME_UNRESOLVED");
    expect(logged.join("\n")).toContain("has no literal scene name.");
  });

  it("a dev rescan writes the new scene names and reloads", async () => {
    writeFileSync(join(root, "gwen.config.ts"), "export default { modules: [] };\n");
    const scenePath = join(root, "src", "scenes", "a.ts");
    writeScene(root, "a.ts", 'export const A = defineScene("lobby", () => {});\n');
    const plugins = gwen({ watch: false });
    const plugin = plugins.find((item) => item.name === "gwen");
    if (plugin === undefined) throw new Error('gwen() did not return the "gwen" plugin');

    const configResolved = plugin.configResolved;
    if (typeof configResolved !== "function") throw new Error("gwen plugin has no configResolved");
    Reflect.apply(configResolved, plugin, [{ root }]);

    const buildStart = plugin.buildStart;
    if (typeof buildStart !== "function") throw new Error("gwen plugin has no buildStart");
    await Reflect.apply(buildStart, plugin, []);

    writeFileSync(scenePath, 'export const A = defineScene("play", () => {});\n');
    const sent: { type: string }[] = [];
    const watcher = new FakeWatcher();
    const server = {
      config: {
        root,
        logger: {
          error(_message: string): void {},
        },
      },
      watcher,
      moduleGraph: {
        getModuleById(): null {
          return null;
        },
        invalidateModule(): void {},
      },
      ws: {
        send(payload: { type: string }): void {
          sent.push(payload);
        },
      },
      middlewares: {
        use(): void {},
      },
    };
    const configureServer = plugin.configureServer;
    if (typeof configureServer !== "function") {
      throw new Error("gwen plugin has no configureServer");
    }
    Reflect.apply(configureServer, plugin, [server]);
    watcher.emit("change", scenePath);

    const file = scenesFile(root);
    expect(existsSync(file)).toBe(true);
    expect(readFileSync(file, "utf8")).toBe(generateScenesDts(["play"]));
    expect(sent).toEqual([{ type: "full-reload" }]);
  });
});
