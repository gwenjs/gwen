// Generates src/framework-ranges.generated.ts: one dependency range per package of the
// release-please manifest. A package of the single linked group maps to CORE_RANGE.
// Every other package maps to "^" plus its manifest version.
// Usage: node scripts/generate-framework-ranges.mjs [--stdout] [--check] [--root <dir>] [--out <file>]
// --check writes nothing: it exits 1 and names the file when it differs from the generator output.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = path.resolve(here, "../../..");
const DEFAULT_OUT = path.resolve(here, "../src/framework-ranges.generated.ts");

function compareText(left, right) {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

function readErrorCode(error) {
  return typeof error === "object" && error !== null && "code" in error ? error.code : undefined;
}

function parseArguments(argv) {
  const options = { stdout: false, check: false, root: DEFAULT_ROOT, out: DEFAULT_OUT };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--stdout") {
      options.stdout = true;
    } else if (argument === "--check") {
      options.check = true;
    } else if (argument === "--root" || argument === "--out") {
      const value = argv[index + 1];
      if (value === undefined || value.startsWith("--"))
        throw new Error(`${argument} needs a value`);
      options[argument.slice(2)] = path.resolve(value);
      index += 1;
    } else {
      throw new Error(`unknown argument ${argument}`);
    }
  }
  if (options.stdout && options.check) throw new Error("cannot combine --stdout and --check");
  return options;
}

async function readJson(file) {
  const text = await readFile(file, "utf8");
  return JSON.parse(text);
}

function linkedGroups(config) {
  if (typeof config !== "object" || config === null) return [];
  const raw = config["linked-versions"];
  if (raw === undefined) return [];
  if (!Array.isArray(raw)) {
    throw new Error("release-please-config.json: linked-versions is not an array");
  }
  return raw;
}

function stringList(value) {
  return Array.isArray(value) && value.length > 0 && value.every((x) => typeof x === "string");
}

function linkedSet(groups, manifest) {
  if (groups.length !== 1) {
    throw new Error(
      `release-please-config.json: expected one linked-versions group, found ${groups.length}`,
    );
  }
  const group = groups[0];
  const components =
    group !== null && typeof group === "object" && !Array.isArray(group) ? group.components : [];
  if (!stringList(components)) {
    throw new Error("release-please-config.json: linked-versions group has no components");
  }
  for (const component of components) {
    if (!Object.hasOwn(manifest, component)) {
      throw new Error(
        `release-please-config.json: linked component "${component}" is not in .release-please-manifest.json`,
      );
    }
  }
  return new Set(components);
}

function packageName(manifestPath, config) {
  const packages = typeof config === "object" && config !== null ? config.packages : undefined;
  const entry =
    typeof packages === "object" && packages !== null ? packages[manifestPath] : undefined;
  const name = typeof entry === "object" && entry !== null ? entry["package-name"] : undefined;
  if (typeof name !== "string") {
    throw new Error(
      `.release-please-manifest.json: "${manifestPath}" has no package-name in release-please-config.json`,
    );
  }
  return name;
}

function rangeToken(manifestPath, version, linked) {
  if (typeof version !== "string") {
    throw new Error(`.release-please-manifest.json: "${manifestPath}" has no string version`);
  }
  if (linked.has(manifestPath)) return "CORE_RANGE";
  return JSON.stringify(`^${version}`);
}

function buildEntries(manifest, config) {
  if (typeof manifest !== "object" || manifest === null || Array.isArray(manifest)) {
    throw new Error(".release-please-manifest.json: expected an object of package paths");
  }
  const linked = linkedSet(linkedGroups(config), manifest);
  const entries = [];
  for (const manifestPath of Object.keys(manifest)) {
    entries.push({
      name: packageName(manifestPath, config),
      token: rangeToken(manifestPath, manifest[manifestPath], linked),
    });
  }
  entries.sort((left, right) => compareText(left.name, right.name));
  return entries;
}

function render(entries) {
  const lines = [
    "// Generated by scripts/generate-framework-ranges.mjs from .release-please-manifest.json and",
    "// release-please-config.json. Do not edit.",
    'import { CORE_RANGE } from "./core-range";',
    "",
    "export const FRAMEWORK_RANGES: Readonly<Record<string, string>> = Object.freeze({",
  ];
  for (const entry of entries) {
    lines.push(`  ${JSON.stringify(entry.name)}: ${entry.token},`);
  }
  lines.push("});", "");
  return lines.join("\n");
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const manifest = await readJson(path.join(options.root, ".release-please-manifest.json"));
  const config = await readJson(path.join(options.root, "release-please-config.json"));
  const text = render(buildEntries(manifest, config));
  if (options.stdout) {
    process.stdout.write(text);
    return;
  }
  if (options.check) {
    const committed = await readFile(options.out, "utf8").catch((error) => {
      if (readErrorCode(error) === "ENOENT") return undefined;
      throw error;
    });
    if (committed !== text) {
      throw new Error(`${options.out} is out of date: run "pnpm generate" and commit it`);
    }
    return;
  }
  await mkdir(path.dirname(options.out), { recursive: true });
  await writeFile(options.out, text);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
