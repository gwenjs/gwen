/** Generator for framework-ranges.generated.ts (#281). The script is executed, never imported. */
import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

import { describe, expect, it } from "vitest";

const run = promisify(execFile);
const here = path.dirname(fileURLToPath(import.meta.url));
const script = path.resolve(here, "../scripts/generate-framework-ranges.mjs");
const packageManifest = path.resolve(here, "../package.json");

const HEADER = [
  "// Generated by scripts/generate-framework-ranges.mjs from .release-please-manifest.json and",
  "// release-please-config.json. Do not edit.",
].join("\n");

interface Fixture {
  readonly manifest: Readonly<Record<string, string>>;
  readonly config: {
    readonly packages: Readonly<Record<string, { readonly "package-name": string }>>;
    readonly "linked-versions"?: readonly { name: string; components: readonly string[] }[];
  };
}

function expectedSource(rows: readonly (readonly [string, string])[]): string {
  const body = [
    'import { CORE_RANGE } from "./core-range";',
    "",
    "export const FRAMEWORK_RANGES: Readonly<Record<string, string>> = Object.freeze({",
    ...rows.map(([name, token]) => `  ${JSON.stringify(name)}: ${token},`),
    "});",
    "",
  ].join("\n");
  return `${HEADER}\n${body}`;
}

function caret(version: string): string {
  return JSON.stringify(`^${version}`);
}

function mixedFixture(): Fixture {
  return {
    manifest: {
      "packages/zeta": "1.2.3",
      "packages/alpha": "0.4.0",
      "packages/mid": "9.0.0",
      "packages/beta": "4.5.6",
    },
    config: {
      "linked-versions": [{ name: "group", components: ["packages/zeta", "packages/alpha"] }],
      packages: {
        "packages/mid": { "package-name": "@gwenjs/mid" },
        "packages/zeta": { "package-name": "@gwenjs/zeta" },
        "packages/beta": { "package-name": "@gwenjs/beta" },
        "packages/alpha": { "package-name": "@gwenjs/alpha" },
      },
    },
  };
}

function caretFixture(): Fixture {
  return {
    manifest: { "packages/beta": "2.0.0", "packages/alpha": "1.0.0" },
    config: {
      "linked-versions": [{ name: "group", components: ["packages/beta"] }],
      packages: {
        "packages/beta": { "package-name": "@gwenjs/beta" },
        "packages/alpha": { "package-name": "@gwenjs/alpha" },
      },
    },
  };
}

async function writeRaw(root: string, manifest: unknown, config: unknown): Promise<void> {
  await writeFile(
    path.join(root, ".release-please-manifest.json"),
    `${JSON.stringify(manifest)}\n`,
  );
  await writeFile(path.join(root, "release-please-config.json"), `${JSON.stringify(config)}\n`);
}

async function writeFixture(root: string, fixture: Fixture): Promise<void> {
  await writeRaw(root, fixture.manifest, fixture.config);
}

async function expectUnwritten(
  root: string,
  manifest: unknown,
  config: unknown,
  stderr: string,
  args?: readonly string[],
): Promise<void> {
  await writeRaw(root, manifest, config);
  const out = path.join(root, "out.ts");
  const result = await runScript(args ?? ["--root", root, "--out", out]);
  expect(result.stderr).toBe(stderr);
  expect(result.code).toBe(1);
  await expect(readFile(out, "utf8")).rejects.toMatchObject({ code: "ENOENT" });
}

async function withTree(body: (root: string) => Promise<void>): Promise<void> {
  const root = await mkdtemp(path.join(tmpdir(), "gwen-framework-ranges-"));
  try {
    await body(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

async function runScript(args: readonly string[]) {
  try {
    const { stdout, stderr } = await run(process.execPath, [script, ...args]);
    return { code: 0, stdout, stderr };
  } catch (error) {
    if (typeof error !== "object" || error === null) return { code: -1, stdout: "", stderr: "" };
    const code = "code" in error && typeof error.code === "number" ? error.code : -1;
    const stdout = "stdout" in error && typeof error.stdout === "string" ? error.stdout : "";
    const stderr = "stderr" in error && typeof error.stderr === "string" ? error.stderr : "";
    return { code, stdout, stderr };
  }
}

describe("generate-framework-ranges", () => {
  it("prints sorted names, the caret of the manifest version and CORE_RANGE for the linked group", async () => {
    await withTree(async (root) => {
      await writeFixture(root, mixedFixture());
      const result = await runScript(["--stdout", "--root", root]);
      expect(result.code).toBe(0);
      expect(result.stdout).toBe(
        expectedSource([
          ["@gwenjs/alpha", "CORE_RANGE"],
          ["@gwenjs/beta", caret("4.5.6")],
          ["@gwenjs/mid", caret("9.0.0")],
          ["@gwenjs/zeta", "CORE_RANGE"],
        ]),
      );
    });
  });

  it("rejects a config with no linked group", async () => {
    const manifest = { "packages/a": "1.0.0" };
    const packages = { "packages/a": { "package-name": "@gwenjs/a" } };
    const stderr = "release-please-config.json: expected one linked-versions group, found 0\n";
    await withTree(async (root) => {
      await expectUnwritten(root, manifest, { packages }, stderr);
      await expectUnwritten(root, manifest, { packages, "linked-versions": [] }, stderr);
    });
  });

  it("--check passes on the committed file", async () => {
    const result = await runScript(["--check"]);
    expect(result).toEqual({ code: 0, stdout: "", stderr: "" });
  });

  it("--check exits 1, names the file and leaves it untouched when a manifest version moved", async () => {
    await withTree(async (root) => {
      await writeFixture(root, caretFixture());
      const out = path.join(root, "ranges.ts");
      const written = await runScript(["--root", root, "--out", out]);
      expect(written.code).toBe(0);
      const before = await readFile(out, "utf8");
      await writeFile(
        path.join(root, ".release-please-manifest.json"),
        `${JSON.stringify({ "packages/beta": "2.0.0", "packages/alpha": "9.9.9" }, null, 2)}\n`,
      );
      const result = await runScript(["--check", "--root", root, "--out", out]);
      expect(result.stderr).toBe(`${out} is out of date: run "pnpm generate" and commit it\n`);
      expect(result.code).toBe(1);
      expect(await readFile(out, "utf8")).toBe(before);
    });
  });

  it("--check exits 1 and does not create a missing file", async () => {
    await withTree(async (root) => {
      await writeFixture(root, caretFixture());
      const out = path.join(root, "missing.ts");
      const result = await runScript(["--check", "--root", root, "--out", out]);
      expect(result.stderr).toBe(`${out} is out of date: run "pnpm generate" and commit it\n`);
      expect(result.code).toBe(1);
      await expect(readFile(out, "utf8")).rejects.toMatchObject({ code: "ENOENT" });
    });
  });

  it("--out writes the file and prints nothing", async () => {
    await withTree(async (root) => {
      await writeFixture(root, mixedFixture());
      const out = path.join(root, "nested", "ranges.ts");
      const written = await runScript(["--root", root, "--out", out]);
      expect(written.code).toBe(0);
      expect(written.stdout).toBe("");
      expect(written.stderr).toBe("");
      const printed = await runScript(["--stdout", "--root", root]);
      expect(await readFile(out, "utf8")).toBe(printed.stdout);
    });
  });

  it("names the manifest path when it has no package-name in the config", async () => {
    await withTree((root) =>
      expectUnwritten(
        root,
        { "packages/ghost": "1.0.0" },
        { packages: {}, "linked-versions": [{ name: "g", components: ["packages/ghost"] }] },
        '.release-please-manifest.json: "packages/ghost" has no package-name in release-please-config.json\n',
      ),
    );
  });

  it("names the component when a linked component is not in the manifest", async () => {
    await withTree((root) =>
      expectUnwritten(
        root,
        { "packages/real": "1.0.0" },
        {
          "linked-versions": [{ name: "group", components: ["packages/ghost"] }],
          packages: { "packages/real": { "package-name": "@gwenjs/real" } },
        },
        'release-please-config.json: linked component "packages/ghost" is not in .release-please-manifest.json\n',
      ),
    );
  });

  it("rejects a config with more than one linked group", async () => {
    await withTree((root) =>
      expectUnwritten(
        root,
        { "packages/a": "1.0.0", "packages/b": "2.0.0" },
        {
          "linked-versions": [
            { name: "one", components: ["packages/a"] },
            { name: "two", components: ["packages/b"] },
          ],
          packages: {
            "packages/a": { "package-name": "@gwenjs/a" },
            "packages/b": { "package-name": "@gwenjs/b" },
          },
        },
        "release-please-config.json: expected one linked-versions group, found 2\n",
      ),
    );
  });

  it("rejects a linked group with no components", async () => {
    const manifest = { "packages/a": "1.0.0" };
    const packages = { "packages/a": { "package-name": "@gwenjs/a" } };
    const stderr = "release-please-config.json: linked-versions group has no components\n";
    const groups: readonly unknown[] = [
      { name: "g" },
      { name: "g", components: [] },
      { name: "g", components: "packages/a" },
      { name: "g", components: [1] },
      null,
      "g",
      ["packages/a"],
    ];
    await withTree(async (root) => {
      for (const group of groups) {
        await expectUnwritten(root, manifest, { packages, "linked-versions": [group] }, stderr);
      }
    });
  });

  it("rejects a manifest entry whose version is not a string", async () => {
    const config = {
      packages: {
        "packages/a": { "package-name": "@gwenjs/a" },
        "packages/b": { "package-name": "@gwenjs/b" },
      },
      "linked-versions": [{ name: "g", components: ["packages/b"] }],
    };
    const stderr = '.release-please-manifest.json: "packages/a" has no string version\n';
    await withTree(async (root) => {
      for (const version of [1, { v: 1 }]) {
        await expectUnwritten(
          root,
          { "packages/a": version, "packages/b": "2.0.0" },
          config,
          stderr,
        );
      }
    });
  });

  it("rejects bad arguments", async () => {
    await withTree(async (root) => {
      const out = path.join(root, "out.ts");
      const rows: readonly (readonly [readonly string[], string])[] = [
        [["--stdout", "--check"], "cannot combine --stdout and --check\n"],
        [["--check", "--stdout"], "cannot combine --stdout and --check\n"],
        [["--root", "--check"], "--root needs a value\n"],
        [["--out", "--check"], "--out needs a value\n"],
        [["--root"], "--root needs a value\n"],
        [["--out"], "--out needs a value\n"],
        [["--also", "--out", out], "unknown argument --also\n"],
      ];
      for (const [args, stderr] of rows) await expectUnwritten(root, {}, {}, stderr, args);
    });
  });

  it("rejects a malformed config or manifest", async () => {
    const packages = { "packages/a": { "package-name": "@gwenjs/a" } };
    const linked = { packages, "linked-versions": [{ name: "g", components: ["packages/a"] }] };
    const manifest = { "packages/a": "1.0.0" };
    const notArray = "release-please-config.json: linked-versions is not an array\n";
    const badManifest = ".release-please-manifest.json: expected an object of package paths\n";
    const foundZero = "release-please-config.json: expected one linked-versions group, found 0\n";
    await withTree(async (root) => {
      await expectUnwritten(root, manifest, null, foundZero);
      await expectUnwritten(root, manifest, { packages, "linked-versions": {} }, notArray);
      await expectUnwritten(root, [], linked, badManifest);
      await expectUnwritten(root, null, linked, badManifest);
    });
  });

  it("runs --check before build and keeps generate for writing", async () => {
    const parsed = JSON.parse(await readFile(packageManifest, "utf8")) as {
      scripts: Record<string, string>;
    };
    expect(parsed.scripts.generate).toBe("node scripts/generate-framework-ranges.mjs");
    expect(parsed.scripts.prebuild).toBe("node scripts/generate-framework-ranges.mjs --check");
  });
});
