/**
 * @file gwen:physics3d — Vite plugin for layer inlining and BVH pre-baking.
 */
import type { Plugin } from "vite";
import { GwenError } from "@gwenjs/schema";
import { createBvhPrebakeTransform, layerInlineTransform } from "@gwenjs/vite/shared/layer-utils";
import { Physics3DErrorCodes } from "./errors/codes";

/**
 * Options accepted by {@link physics3dVitePlugin}.
 */
export interface GwenPhysics3DPluginOptions {
  /**
   * Enable BVH pre-baking for `useMeshCollider('./file.glb')` patterns.
   * Requires the `physics3d/build-tools` Node.js WASM to be built first.
   * @default false
   */
  bvhPrebake?: boolean;
}

// ─── BVH pre-baking support ───────────────────────────────────────────────────

/** Lazy-loaded build-tools WASM module (Node.js target). */
let buildToolsWasm: {
  build_bvh_from_glb: (bytes: Uint8Array, name?: string) => Uint8Array;
} | null = null;

/**
 * Injectable loader override for build-tools WASM — used in tests to inject a mock
 * without requiring the actual `build-tools/gwen_core.js` binary.
 * @internal
 */
let _buildToolsLoaderOverride:
  | (() => Promise<{
      build_bvh_from_glb: (bytes: Uint8Array, name?: string) => Uint8Array;
    }>)
  | null = null;

/**
 * Set a custom build-tools loader. Call it before a module that bakes is transformed.
 * Clears the module-level cache so the new loader is used on the next call.
 *
 * @param loader - Async factory returning a build-tools-like object.
 *
 * @internal Exported for unit tests only — do not call in production code.
 */
export function _setBuildToolsLoader(
  loader: () => Promise<{
    build_bvh_from_glb: (bytes: Uint8Array, name?: string) => Uint8Array;
  }>,
): void {
  _buildToolsLoaderOverride = loader;
  buildToolsWasm = null; // reset so the new loader is picked up
}

/**
 * Lazily import and initialise the build-tools WASM module.
 * Cached after first call — subsequent calls are instant.
 *
 * @internal
 */
async function getBuildTools(): Promise<{
  build_bvh_from_glb: (bytes: Uint8Array, name?: string) => Uint8Array;
}> {
  if (buildToolsWasm) return buildToolsWasm;
  if (_buildToolsLoaderOverride) {
    buildToolsWasm = await _buildToolsLoaderOverride();
    return buildToolsWasm;
  }
  // build-tools/gwen_core.js is generated by scripts/build-wasm.sh.
  // The Node glue instantiates WASM on import, so there is no default init.
  const mod = await import("../build-tools/gwen_core");
  buildToolsWasm = mod;
  return mod;
}

const bakedAssets = new Map<string, Uint8Array>();

async function bakeWithBuildTools(
  bytes: Uint8Array,
  mesh: string | undefined,
): Promise<Uint8Array> {
  const tools = await getBuildTools();
  return tools.build_bvh_from_glb(bytes, mesh);
}

const bvhPrebakeTransform = createBvhPrebakeTransform({
  bake: bakeWithBuildTools,
  assets: bakedAssets,
});

function stripQuery(url: string): string {
  const queryAt = url.indexOf("?");
  if (queryAt < 0) return url;
  return url.slice(0, queryAt);
}

function nameUnderBase(pathname: string, base: string): string | undefined {
  if (!pathname.startsWith(base)) return undefined;
  const name = pathname.slice(base.length);
  if (name.length === 0) return undefined;
  return name;
}

interface PipelineUnit {
  readonly name: string;
}

function isPipelineRegister(value: unknown): value is (unit: PipelineUnit) => void {
  return typeof value === "function";
}

function pipelineApi(
  plugins: readonly Plugin[],
): { register: (unit: PipelineUnit) => void } | undefined {
  for (const plugin of plugins) {
    if (plugin.name !== "gwen:transform-pipeline") continue;
    const candidate: unknown = plugin.api;
    if (typeof candidate !== "object" || candidate === null || !("register" in candidate)) {
      return undefined;
    }
    const register: unknown = candidate.register;
    if (!isPipelineRegister(register)) return undefined;
    return { register };
  }
  return undefined;
}

/**
 * `gwen:physics3d` — Vite plugin for Physics 3D build-time optimizations.
 *
 * Performs the following transformations:
 * - **Layer inlining**: registers `gwen:layer-inline` on `gwen:transform-pipeline`.
 *   `gwen()` must be in the Vite config.
 * - **BVH pre-baking** (opt-in via `bvhPrebake: true`): registers `gwen:bvh-prebake`.
 *   A relative `useMeshCollider("./file.glb")` becomes `{ __bvhUrl: "bvh-<hash>.bin" }`.
 *   Dev serves that asset from memory.
 *
 * Registered automatically by the `physics3dModule` when added to the GWEN config.
 * Can also be added manually to a plain Vite config:
 *
 * @example
 * ```typescript
 * // vite.config.ts
 * import { gwen } from '@gwenjs/vite'
 * import { physics3dVitePlugin } from '@gwenjs/physics3d/module'
 *
 * export default {
 *   plugins: [gwen(), physics3dVitePlugin({ bvhPrebake: true })],
 * }
 * ```
 *
 * @param options - Plugin options.
 * @returns A Vite {@link Plugin} object.
 *
 * @since 1.0.0
 */
export function physics3dVitePlugin(options: GwenPhysics3DPluginOptions = {}): Plugin {
  const { bvhPrebake = false } = options;
  let assetBase = "/";

  return {
    name: "gwen:physics3d",

    configResolved(config) {
      assetBase = config.base;
      const api = pipelineApi(config.plugins);
      if (api === undefined) {
        throw new GwenError(
          Physics3DErrorCodes.VITE_PIPELINE_MISSING,
          "gwen:transform-pipeline is not in the Vite config.",
          {
            composable: "physics3dVitePlugin",
            hint:
              process.env["NODE_ENV"] !== "production"
                ? "Add gwen() from @gwenjs/vite before the physics plugin."
                : undefined,
          },
        );
      }
      api.register(layerInlineTransform);
      if (bvhPrebake) api.register(bvhPrebakeTransform);
    },

    configureServer(server) {
      if (!bvhPrebake) return;
      const base = assetBase;
      server.middlewares.use((req, res, next) => {
        if (req.method !== "GET") {
          next();
          return;
        }
        const url = req.url;
        if (typeof url !== "string") {
          next();
          return;
        }
        const name = nameUnderBase(stripQuery(url), base);
        if (name === undefined) {
          next();
          return;
        }
        const bytes = bakedAssets.get(name);
        if (bytes === undefined) {
          next();
          return;
        }
        res.setHeader("Content-Type", "application/octet-stream");
        res.setHeader("Cache-Control", "no-cache");
        res.statusCode = 200;
        res.end(bytes);
      });
    },
  };
}
