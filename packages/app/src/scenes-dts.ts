/**
 * Generated `.gwen/types/scenes.d.ts`.
 * Pure string output plus the idempotent writer `GwenApp.prepare` and the Vite plugin share.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Writes `content` to `filePath` only when the file does not already hold it.
 * Unchanged files keep their mtime so TypeScript does not recheck them.
 */
export function writeIfChanged(filePath: string, content: string): void {
  if (existsSync(filePath)) {
    const current = readFileSync(filePath, "utf8");
    if (current === content) return;
  }
  writeFileSync(filePath, content, "utf8");
}

/**
 * `scenes.d.ts` source for `names`.
 * Names are sorted. Each key is `JSON.stringify`'d so quotes stay escaped.
 * An empty list emits `interface GwenSceneRegistry {}`.
 */
export function generateScenesDts(names: readonly string[]): string {
  const sorted = [...names].sort();
  const body =
    sorted.length === 0
      ? ""
      : ` ${sorted.map((name) => `${JSON.stringify(name)}: true`).join("; ")} `;
  return [
    "// .gwen/types/scenes.d.ts — generated by GWEN, do not edit",
    'declare module "@gwenjs/schema" {',
    `  interface GwenSceneRegistry {${body}}`,
    "}",
    "export {};",
    "",
  ].join("\n");
}

/** Write `<projectRoot>/.gwen/types/scenes.d.ts` when the text changed. */
export function writeScenesDts(projectRoot: string, names: readonly string[]): void {
  const typesDir = join(projectRoot, ".gwen", "types");
  mkdirSync(typesDir, { recursive: true });
  writeIfChanged(join(typesDir, "scenes.d.ts"), generateScenesDts(names));
}
