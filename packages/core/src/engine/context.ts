/**
 * @file RFC-005 — Composable context system for @gwenjs/core
 *
 * Provides `engineContext` (backed by unctx) and the `useEngine()` composable.
 * The engine wraps its entire frame loop and plugin setup calls in this context,
 * making composables available without explicit parameter passing.
 */

import { createContext } from "unctx";
import { GwenContextError, GwenContextErrorCodes } from "@gwenjs/kit";
import type { GwenEngine } from "./engine-types";
import { GwenScope } from "../context/scope.js";

export { GwenContextError, GwenContextErrorCodes };
export type { GwenContextErrorCode } from "@gwenjs/kit";

// ─── Context ─────────────────────────────────────────────────────────────────

/**
 * The global engine context backed by unctx.
 *
 * Uses a simple synchronous (non-async) context for browser compatibility.
 * Active during:
 * - `engine.run(fn)` — explicit context scoping
 * - `engine.activate()` / `engine.deactivate()` — manual lifecycle
 * - All 8 frame phases inside `_runFrame()` (onBeforeUpdate, onUpdate, onAfterUpdate, onRender…)
 * - Plugin `setup()` calls inside `engine.use()`
 *
 * @internal — import `useEngine()` instead for public usage
 */
export const engineContext = createContext<GwenEngine>({
  asyncContext: false,
});

// ─── Async context helpers ────────────────────────────────────────────────────

/**
 * Captures the current engine context and {@link GwenScope} and returns a
 * `[promise, restore]` tuple.
 *
 * Used internally by the `@gwenjs/vite` async context transform — injected
 * around every `await` inside `onEnter`, `onExit`, and `withAsyncContext`
 * callbacks to preserve both the engine context and scope across async
 * suspension points.
 *
 * **Phase 3 (GwenScope):** Also captures and restores the current
 * {@link GwenScope} (if any) to support hook subscriptions and cleanup
 * across await boundaries.
 *
 * @example Generated by the Vite transform (do not write by hand):
 * ```ts
 * // await loadAssets()  →  becomes:
 * ;(([__temp,__restore]=executeAsync(()=>loadAssets())),await __temp,__restore());
 * ```
 */
export function executeAsync<T>(fn: () => Promise<T>): [Promise<T>, () => void] {
  const _ctx = engineContext.tryUse();
  const _scope = GwenScope.current();
  return [
    fn(),
    () => {
      if (_ctx !== null && _ctx !== undefined) {
        engineContext.set(_ctx, true);
      } else {
        engineContext.unset();
      }
      GwenScope._setCurrent(_scope);
    },
  ];
}

/**
 * Opt-in wrapper that preserves engine context and {@link GwenScope} across
 * `await` boundaries inside an async callback. Use when you need to call
 * composables after `await` in a context that is NOT automatically handled
 * (`onStart`, plugin callbacks, etc.).
 *
 * **Requires `@gwenjs/vite` in your Vite config.** The build-time transform
 * instruments the `await` calls inside the wrapped function.
 *
 * Prefer the **capture pattern** when possible — it has zero overhead and no
 * transform dependency:
 * ```ts
 * onStart(async () => {
 *   const html = useHTML()  // ✅ capture before first await
 *   await doSomething()
 *   html.mount()
 * })
 * ```
 *
 * Use `withAsyncContext` only when you must call a composable after `await`:
 * ```ts
 * import { withAsyncContext } from '@gwenjs/core'
 *
 * onStart(withAsyncContext(async () => {
 *   await spawnAnimation()
 *   useHTML().show()  // ✅ context restored
 * }))
 * ```
 *
 * **Phase 3 (GwenScope):** Also preserves the current {@link GwenScope}
 * to ensure hooks and cleanup work correctly after `await`.
 *
 * @param fn - An async function that will be called later (e.g., passed to
 *   `onStart`). Must be defined inside an active engine context so the engine
 *   reference can be captured.
 *
 * @returns A wrapped version of `fn` that restores the captured engine context
 *   and scope when invoked.
 *
 * @throws {GwenContextError} At invocation time if the captured context was
 *   null (i.e., `withAsyncContext` was called outside any engine context).
 */
export function withAsyncContext<T extends (...args: unknown[]) => Promise<unknown>>(fn: T): T {
  const _ctx = engineContext.tryUse();
  const _scope = GwenScope.current();
  return ((...args: unknown[]) => {
    if (_ctx === null || _ctx === undefined) {
      throw new GwenContextError(GwenContextErrorCodes.OUTSIDE_ENGINE_CONTEXT, "withAsyncContext");
    }
    const previousEngine = engineContext.tryUse();
    const previousScope = GwenScope.current();
    engineContext.set(_ctx, true);
    GwenScope._setCurrent(_scope);
    return fn(...args).finally(() => {
      if (engineContext.tryUse() !== _ctx) return;
      if (previousEngine) engineContext.set(previousEngine, true);
      else engineContext.unset();
      GwenScope._setCurrent(previousScope);
    });
  }) as T;
}

// ─── useEngine() ─────────────────────────────────────────────────────────────

/**
 * Returns the currently active {@link GwenEngine} instance.
 *
 * Must be called within an active engine context:
 * - Inside `defineSystem()` factory or any of its frame hooks
 * - Inside `defineScene()` factory
 * - Inside `engine.run(fn)`
 * - Inside `onEnter()` or `onExit()` (sync or async — handled by Vite transform)
 * - Inside `withAsyncContext()` wrapper
 *
 * @param composable - Name reported when no engine is current. Defaults to `useEngine`.
 * @throws {GwenContextError} `CORE:OUTSIDE_ENGINE_CONTEXT` when no engine is current.
 *   `composable` and `validContexts` name the call and the valid contexts.
 *
 * @example Inside engine.run():
 * ```typescript
 * const instance = engine.run(() => useEngine()) // instance === engine ✓
 * ```
 *
 * @example Inside defineSystem():
 * ```typescript
 * const mySystem = defineSystem(() => {
 *   const engine = useEngine()
 *   onUpdate((dt) => { /* engine available here too *\/ })
 * })
 * ```
 *
 * @example Inside async onEnter (requires \@gwenjs/vite):
 * ```typescript
 * const Scene = defineScene('game', () => {
 *   onEnter(async () => {
 *     await loadAssets()
 *     const engine = useEngine() // ✅ context restored by Vite transform
 *   })
 * })
 * ```
 */
export function useEngine(composable = "useEngine"): GwenEngine {
  const engine = engineContext.tryUse();
  if (!engine) {
    throw new GwenContextError(GwenContextErrorCodes.OUTSIDE_ENGINE_CONTEXT, composable);
  }
  return engine;
}
